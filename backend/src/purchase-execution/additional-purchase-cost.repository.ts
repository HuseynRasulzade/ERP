import { Injectable } from '@nestjs/common';
import { PrismaService, PrismaTransactionClient } from '../prisma/prisma.service';
import { DocumentRepositoryAdapter, DocumentStatusPatch } from '../document-framework/document-repository.interface';
import { BaseDocumentFields } from '../document-framework/base-document';

export const ADDITIONAL_PURCHASE_COST_TYPE = 'ADDITIONAL_PURCHASE_COST';

@Injectable()
export class AdditionalPurchaseCostRepository implements DocumentRepositoryAdapter {
  readonly documentType = ADDITIONAL_PURCHASE_COST_TYPE;

  constructor(private readonly prisma: PrismaService) {}

  async findById(tenantId: string, id: string, tx?: PrismaTransactionClient): Promise<BaseDocumentFields | null> {
    const client = tx ?? this.prisma;
    const row = await client.additionalPurchaseCost.findFirst({ where: { id, tenantId } });
    return row ? this.toBaseFields(row) : null;
  }

  async applyStatusPatch(tenantId: string, id: string, patch: DocumentStatusPatch, expectedVersion: number, tx: PrismaTransactionClient) {
    const result = await tx.additionalPurchaseCost.updateMany({
      where: { id, tenantId, version: expectedVersion },
      data: {
        ...(patch.status ? { status: patch.status } : {}),
        ...(patch.postingStatus ? { postingStatus: patch.postingStatus } : {}),
        ...(patch.postedAt !== undefined ? { postedAt: patch.postedAt } : {}),
        ...(patch.postedBy !== undefined ? { postedBy: patch.postedBy } : {}),
        version: { increment: 1 },
      },
    });
    return { updatedCount: result.count, newVersion: expectedVersion + 1 };
  }

  async create(_tenantId: string, _input: Record<string, unknown>, _createdBy: string, _tx: PrismaTransactionClient): Promise<BaseDocumentFields> {
    // Always created through AdditionalPurchaseCostService — not part of
    // any Create Based On chain in this build (see docs/PURCHASE_EXECUTION.md
    // Technical Debt: the target-lines/supplier/totalCost combination has
    // no sensible 1:1 header mapping from a single source document).
    throw new Error('Use AdditionalPurchaseCostService.create()');
  }

  private toBaseFields(row: any): BaseDocumentFields {
    return {
      id: row.id,
      tenantId: row.tenantId,
      organizationId: row.organizationId,
      documentType: row.documentType,
      number: row.number,
      documentDate: row.documentDate,
      postingDate: row.postingDate,
      status: row.status,
      postingStatus: row.postingStatus,
      currencyId: row.currencyId,
      exchangeRate: null,
      description: row.description,
      createdAt: row.createdAt,
      createdBy: row.createdBy,
      updatedAt: row.updatedAt,
      updatedBy: row.updatedBy,
      postedAt: row.postedAt,
      postedBy: row.postedBy,
      cancelledAt: null,
      cancelledBy: null,
      deletionMark: false,
      version: row.version,
    };
  }
}
